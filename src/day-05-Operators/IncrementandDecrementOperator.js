/*
For the increment operator, 
    prefix is ++x  &
    postfix is x++.
*/
// prefix
let x = 5;
console.log(++x); // 6
console.log(x); // 6
//postfix
let y = 5;
console.log(y++); // 5
console.log(y); // 6

// decrement operator
let x = 5;
console.log(--x); // 4
console.log(x); // 4

let y = 5;
console.log(y--); // 5
console.log(y); // 4
